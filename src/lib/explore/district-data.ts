/**
 * Helper to get an attraction by its unique ID.
 */
export function getAttractionById(id: string): SecularAttraction | undefined {
  return SECULAR_ATTRACTIONS.find((a) => a.id === id);
}

/**
 * Helper to get all attractions for a given district.
 */
export function getAttractionsByDistrict(districtId: string): SecularAttraction[] {
  return SECULAR_ATTRACTIONS.filter((a) => a.districtId === districtId);
}

/**
 * Helper to get all districts for a given administrative division.
 */
export function getDistrictsByDivision(division: AdministrativeDivision): DistrictInfo[] {
  return KARNATAKA_DISTRICTS.filter((d) => d.division === division);
}

/**
 * Helper to search attractions across 31 districts.
 */
export function searchSecularAttractions(query: string): SecularAttraction[] {
  if (!query || query.trim() === "") return SECULAR_ATTRACTIONS;
  const q = query.toLowerCase().trim();
  return SECULAR_ATTRACTIONS.filter(
    (a) =>
      a.nameEn.toLowerCase().includes(q) ||
      a.nameKn.includes(q) ||
      a.districtId.toLowerCase().includes(q) ||
      a.shortDescEn.toLowerCase().includes(q) ||
      a.highlightsEn.some((h) => h.toLowerCase().includes(q))
  );
}
